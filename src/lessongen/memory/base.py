from abc import ABC, abstractmethod


class MemoryStore(ABC):
    """Persistent memory. SQLite today; a pgvector backend could implement this same interface (see README: scaling path)."""

    @abstractmethod
    def record_run(self, run_id: str, topic: str, status: str, attempts: int, tokens: int): ...
    @abstractmethod
    def record_failures(self, counts: dict, last_reason: dict): ...
    @abstractmethod
    def failure_counts(self) -> dict: ...
    @abstractmethod
    def has_lesson(self, check_id: str) -> bool: ...
    @abstractmethod
    def add_lesson(self, check_id: str, text: str, source_run: str): ...
    @abstractmethod
    def active_lessons(self, limit: int = 8) -> list[dict]: ...
    @abstractmethod
    def bump_hits(self, ids: list[int]): ...
    @abstractmethod
    def add_proposal(self, description: str, fix_hint: str, source_run: str) -> int | None: ...
    @abstractmethod
    def proposals(self, status: str = "pending") -> list[dict]: ...
    @abstractmethod
    def set_proposal(self, pid: int, status: str) -> bool: ...
    @abstractmethod
    def approved_checks(self) -> list[dict]: ...
    @abstractmethod
    def runs(self, limit: int = 10) -> list[dict]: ...
